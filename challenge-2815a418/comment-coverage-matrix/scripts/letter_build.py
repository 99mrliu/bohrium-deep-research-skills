def has_cjk(s):
    return any('一' <= ch <= '鿿' for ch in s)


def loc_of(sub, chg_by_sub):
    items = []
    for loc in sub.get("locations", []):
        cid = loc.get("chg_id", "")
        ch = chg_by_sub.get(cid)
        if ch:
            items.append((cid, ch.get("section") or loc.get("section") or "?", ch.get("paragraph") or "?"))
        elif loc.get("section"):
            items.append((cid or "?", loc.get("section"), loc.get("paragraph") or "?"))
    return items


def build(matrix, changes, lang):
    t = T[lang]
    comments = matrix.get("comments", [])
    n_sub = sum(len(c.get("subrequirements", [])) for c in comments)
    by_dec, by_type = {}, {}
    ev_rows = []
    for c in comments:
        for s in c.get("subrequirements", []):
            by_dec.setdefault(s.get("decision", "?"), []).append(s["sub_id"])
            by_type[s.get("type", "?")] = by_type.get(s.get("type", "?"), 0) + 1
    sev_maj = sum(1 for c in comments for s in c["subrequirements"] if s.get("severity") == "major")
    by_type_str = ", ".join("%s %d" % (k, v) for k, v in sorted(by_type.items()))
    chg_by_sub = {ch["chg_id"]: ch for ch in (changes or {}).get("changes", [])}

    L = [t["title"], "", t["meta"].format(case_id=matrix.get("case_id", "UNKNOWN"), rnd=matrix.get("round", 1)), ""]
    L.append(t["summary_h"]); L.append("")
    n_ev = 0
    L.append(t["summary"].format(
        c=len(comments), n=n_sub,
        acc=len(by_dec.get("采纳", [])), part=len(by_dec.get("部分采纳", [])), rej=len(by_dec.get("不采纳", [])),
        by_type=by_type_str or "-", maj=sev_maj, minr=n_sub - sev_maj, ev="?"))
    L.append("")
    L.append(t["detail_h"])
    for c in comments:
        L.append("")
        raw = " ".join(c.get("raw_text", "").split())
        L.append(t["comment_quote"].format(cid=c.get("comment_id", "?"), raw=raw))
        for s in c.get("subrequirements", []):
            L.append("")
            L.append(t["sub_head"].format(sid=s["sub_id"], typ=s.get("type", "?"),
                                          sev=s.get("severity", "?"), act=s.get("action", "?")))
            L.append("")
            L.append(t["quote_lbl"] + "“" + s.get("raw_text", "").strip() + "”")
            L.append("")
            L.append(t["decision_lbl"].format(d=s.get("decision", "?")))
            L.append(t["reason_lbl"].format(r=s.get("decision_reason", "").strip()))
            L.append("")
            L.append(t["resp_lbl"].format(r=s.get("response_summary", "").strip()))
            L.append("")
            items = loc_of(s, chg_by_sub)
            if items:
                L.append(t["loc_lbl"] + "；".join(
                    t["loc_item"].format(chg=cid, sec=sec, para=para) for cid, sec, para in items))
            else:
                L.append(t["loc_lbl"] + t["loc_none"].format(
                    expl=(s.get("no_change_explanation") or "").strip() or "（待补）"))
            if s.get("action") in EVIDENCE_ACTIONS:
                ev = s.get("evidence") or {}
                n_ev += 1
                line = t["ev_lbl"].format(st=ev.get("status", "?"), src=ev.get("source", "") or "—")
                if ev.get("status") == "无法补做":
                    line += t["ev_alt"].format(alt=ev.get("alternative_explanation", ""))
                L.append("")
                L.append(line)
                ev_rows.append([s["sub_id"], s.get("action", ""), ev.get("status", "?"),
                                ev.get("source", "") or "—",
                                (ev.get("alternative_explanation", "") or "—") if ev.get("status") == "无法补做" else "—"])
    # 回填总述中的补做类计数（直接重建总述行）
    for i, ln in enumerate(L):
        if ln.startswith("感谢编辑与审稿人") or ln.startswith("We thank the editor"):
            L[i] = t["summary"].format(
                c=len(comments), n=n_sub,
                acc=len(by_dec.get("采纳", [])), part=len(by_dec.get("部分采纳", [])),
                rej=len(by_dec.get("不采纳", [])),
                by_type=by_type_str or "-", maj=sev_maj, minr=n_sub - sev_maj, ev=n_ev)
    L.append("")
    L.append(t["table1_h"]); L.append("")
    L.append(t["table1_head"])
    for d in ("采纳", "部分采纳", "不采纳"):
        ids = by_dec.get(d, [])
        L.append("| %s | %d | %s |" % (d, len(ids), ", ".join(ids) if ids else "—"))
    L.append("")
    L.append(t["table2_h"]); L.append("")
    if ev_rows:
        L.append(t["table2_head"])
        for r in ev_rows:
            L.append("| " + " | ".join(x.replace("|", "\\|") for x in r) + " |")
    else:
        L.append(t["table2_none"])
    L.append("")
    L.append(t["footer"])
    return "\n".join(L) + "\n", ev_rows


def build_evidence_checklist(matrix, lang):
    zh = lang == "zh"
    L = ["# 未到位证据清单 / Evidence Checklist" if zh else "# Evidence Checklist", ""]
    L.append("> 本清单由 letter_build.py 从覆盖矩阵生成：列出全部补做类子要求的证据状态，重点标出未到位项。" if zh
             else "> Generated from the coverage matrix: evidence status of all sub-requirements needing new work.")
    L.append("")
    any_row = False
    for c in matrix.get("comments", []):
        for s in c.get("subrequirements", []):
            if s.get("action") not in EVIDENCE_ACTIONS:
                continue
            any_row = True
            ev = s.get("evidence") or {}
            st = ev.get("status", "?")
            mark = "✅" if st == "到位" else ("🟡" if st == "部分到位" else "❌")
            L.append("## %s %s（%s）— %s" % (mark, s["sub_id"], s.get("action", ""), st))
            L.append("")
            L.append("- 子要求摘录：%s" % s.get("raw_text", "").strip())
            L.append("- 裁决：%s" % s.get("decision", "?"))
            L.append("- 证据出处：%s" % (ev.get("source", "").strip() or "（未填）"))
            if st != "到位":
                L.append("- **未到位说明 / 替代说明**：%s" % (ev.get("alternative_explanation", "").strip() or "（未填，需作者补充）"))
            L.append("")
    if not any_row:
        L.append("（本轮无补做类子要求）" if zh else "(none)")
        L.append("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description="覆盖矩阵 -> 逐条回复信 + 证据清单")
    ap.add_argument("--matrix", required=True)
    ap.add_argument("--changes", default=None)
    ap.add_argument("--outdir", required=True)
    a = ap.parse_args()
    matrix_path = a.matrix
    # 强制先过 validate
    here = os.path.dirname(os.path.abspath(__file__))
    r = subprocess.run([sys.executable, os.path.join(here, "matrix.py"), "validate", matrix_path],
                       capture_output=True, text=True)
    sys.stdout.write(r.stdout); sys.stderr.write(r.stderr)
    if r.returncode != 0:
        print("[letter_build] FATAL: matrix 未通过 validate，拒绝生成回复信", file=sys.stderr)
        sys.exit(1)
    matrix = json.load(open(matrix_path, encoding="utf-8"))
    changes = None
    if a.changes and os.path.exists(a.changes):
        changes = json.load(open(a.changes, encoding="utf-8"))
    lang = matrix.get("language")
    if lang not in ("zh", "en"):
        sample = " ".join(c.get("raw_text", "") for c in matrix.get("comments", []))
        lang = "zh" if has_cjk(sample) else "en"
    letter, _ = build(matrix, changes, lang)
    checklist = build_evidence_checklist(matrix, lang)
    os.makedirs(a.outdir, exist_ok=True)
    p1 = os.path.join(a.outdir, "response-letter.md")
    p2 = os.path.join(a.outdir, "evidence-checklist.md")
    open(p1, "w", encoding="utf-8").write(letter)
    open(p2, "w", encoding="utf-8").write(checklist)
    n_sub = sum(len(c.get("subrequirements", [])) for c in matrix.get("comments", []))
    print("[letter_build] lang=%s subrequirements=%d -> %s , %s" % (lang, n_sub, p1, p2))


if __name__ == "__main__":
    main()
