#!/usr/bin/env python3
"""result.py - output_contract skeleton / fill / validation for the Harbor run.

Commands:
  result-skeleton  Read a case.json and generate a result.json skeleton that
                   mirrors `output_contract` exactly (all keys, null values,
                   nested keys preserved). Never fabricates content.
  fill             Map produced artifacts onto contract fields, with type
                   conversion; fields that cannot be mapped stay null and are
                   recorded (null honesty).
  validate-result  Check case_id consistency, presence of every contract
                   field, and type conformance for non-null values; nulls are
                   allowed (honest partial) but are reported and must be
                   declared in `_null_fields`.

Python 3 standard library only. Deterministic output.
"""

import argparse
import json
import os
import re
import sys

TYPE_MAP = {
    "string": str,
    "array": list,
    "object": dict,
    "number": (int, float),
    "integer": int,
    "boolean": bool,
}
STATUS_ENUM = ("success", "partial", "blocked")

DEFAULT_UNCERTAINTY = ("Strength cues are heuristic pattern matches; absence "
                       "of flagged drift is not proof of semantic equivalence.")


def _load_json(path):
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def _dump_json(obj, path):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(obj, ensure_ascii=False, indent=2, sort_keys=True))
        fh.write("\n")


def _contract(case):
    contract = case.get("output_contract")
    if not isinstance(contract, dict) or not contract:
        raise SystemExit("case.json has no usable `output_contract` object")
    return contract


def _skeleton_from(contract):
    """null for every declared field; nested objects keep their key shape."""
    skel = {}
    for key, decl in contract.items():
        if isinstance(decl, dict):
            skel[key] = _skeleton_from(decl)
        else:
            skel[key] = None
    return skel


def _type_of(decl):
    if isinstance(decl, str):
        return decl
    return "object"


def _coerce(value, decl_type):
    """Best-effort type conversion; returns (value, ok)."""
    if decl_type not in TYPE_MAP:
        return value, True
    want = TYPE_MAP[decl_type]
    if isinstance(value, want):
        # bool is a subclass of int; keep booleans out of number fields
        if decl_type in ("number", "integer") and isinstance(value, bool):
            return None, False
        return value, True
    if decl_type == "string":
        if isinstance(value, (dict, list)):
            return json.dumps(value, ensure_ascii=False, sort_keys=True), True
        return str(value), True
    return None, False


def _summary_section(report_text):
    """Extract the '## Summary' bullet block from conservation-report.md."""
    m = re.search(r"## Summary\n(.*?)(\n## |\Z)", report_text, re.DOTALL)
    if not m:
        return report_text.strip()
    return "\n".join(line for line in m.group(1).strip().splitlines()
                     if line.strip()).strip()


# ---------------------------------------------------------------------------
# commands
# ---------------------------------------------------------------------------

def cmd_skeleton(args):
    case = _load_json(args.case)
    contract = _contract(case)
    result = _skeleton_from(contract)
    result["case_id"] = case.get("case_id")
    for extra in ("status", "sources", "uncertainty", "notes"):
        result.setdefault(extra, None)
    result["_null_fields"] = sorted(k for k, v in result.items()
                                    if v is None and k != "_null_fields")
    result["notes"] = ("skeleton generated by result.py result-skeleton; "
                       "fill every contract field or leave null and declare it")
    _dump_json(result, args.out)
    print("skeleton with %d contract fields -> %s" % (len(contract), args.out))
    return 0


def cmd_fill(args):
    case = _load_json(args.case)
    result = _load_json(args.result)
    contract = _contract(case)
    notes = []

    def set_field(key, value):
        if key not in contract:
            notes.append("field '%s' not in output_contract; left untouched" % key)
            return
        coerced, ok = _coerce(value, _type_of(contract[key]))
        if ok:
            result[key] = coerced
        else:
            result[key] = None
            notes.append("field '%s' type mismatch (want %s); set to null"
                         % (key, _type_of(contract[key])))

    if args.polished and os.path.exists(args.polished):
        with open(args.polished, "r", encoding="utf-8") as fh:
            set_field("polished_text", fh.read())
    if args.changes and os.path.exists(args.changes):
        set_field("changes", _load_json(args.changes))
    if args.audit and os.path.exists(args.audit):
        set_field("strength_audit", _load_json(args.audit))
    if args.report and os.path.exists(args.report):
        with open(args.report, "r", encoding="utf-8") as fh:
            set_field("conservation_summary", _summary_section(fh.read()))

    if "status" in contract or "status" in result:
        result["status"] = args.status
    if args.sources:
        set_field("sources", args.sources)
        if "sources" not in contract:
            result["sources"] = args.sources
    uncertainty = [DEFAULT_UNCERTAINTY]
    if args.uncertainty:
        uncertainty.extend(args.uncertainty)
    if "uncertainty" in contract:
        set_field("uncertainty", uncertainty)
    else:
        result["uncertainty"] = uncertainty
    if args.notes:
        notes.insert(0, args.notes)
    if notes:
        existing = result.get("notes")
        joined = "; ".join(notes)
        result["notes"] = ("%s | %s" % (existing, joined)) if existing else joined

    result["_null_fields"] = sorted(
        k for k in list(contract) + ["status", "sources", "uncertainty", "notes"]
        if result.get(k) is None)
    _dump_json(result, args.result)
    print("filled %s (null fields: %s)"
          % (args.result, ", ".join(result["_null_fields"]) or "none"))
    return 0


def cmd_validate(args):
    case = _load_json(args.case)
    result = _load_json(args.result)
    contract = _contract(case)
    errors, warnings = [], []

    if result.get("case_id") != case.get("case_id"):
        errors.append("case_id mismatch: result=%r case=%r"
                      % (result.get("case_id"), case.get("case_id")))

    for key, decl in contract.items():
        if key not in result:
            errors.append("missing contract field: %s" % key)
            continue
        value = result[key]
        if value is None:
            if key not in result.get("_null_fields", []):
                warnings.append("field '%s' is null but not declared in "
                                "_null_fields" % key)
            continue
        decl_type = _type_of(decl)
        if decl_type in TYPE_MAP and not isinstance(value, TYPE_MAP[decl_type]):
            errors.append("field '%s' type mismatch: want %s, got %s"
                          % (key, decl_type, type(value).__name__))
        if decl_type in ("number", "integer") and isinstance(value, bool):
            errors.append("field '%s' type mismatch: bool is not %s"
                          % (key, decl_type))

    status = result.get("status")
    if status is None:
        warnings.append("status is null")
    elif status not in STATUS_ENUM:
        errors.append("status must be one of %s, got %r" % (STATUS_ENUM, status))
    if status == "blocked" and result.get("polished_text"):
        warnings.append("status=blocked but polished_text is non-empty")

    for w in warnings:
        print("WARNING: %s" % w)
    if errors:
        for e in errors:
            print("ERROR: %s" % e)
        print("INVALID: %d error(s), %d warning(s)" % (len(errors), len(warnings)))
        return 1
    print("VALID: result.json mirrors output_contract (%d fields, %d warning(s))"
          % (len(contract), len(warnings)))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="result.json skeleton / fill / validation against "
                    "a case.json output_contract.")
    sub = parser.add_subparsers(dest="command", required=True)

    p_sk = sub.add_parser("result-skeleton",
                          help="Generate a null-honest result.json skeleton.")
    p_sk.add_argument("--case", required=True)
    p_sk.add_argument("--out", required=True)
    p_sk.set_defaults(func=cmd_skeleton)

    p_fill = sub.add_parser("fill", help="Map artifacts onto contract fields.")
    p_fill.add_argument("--case", required=True)
    p_fill.add_argument("--result", required=True)
    p_fill.add_argument("--polished", default=None)
    p_fill.add_argument("--changes", default=None)
    p_fill.add_argument("--audit", default=None)
    p_fill.add_argument("--report", default=None)
    p_fill.add_argument("--status", default="partial", choices=STATUS_ENUM)
    p_fill.add_argument("--sources", nargs="*", default=None)
    p_fill.add_argument("--uncertainty", nargs="*", default=None)
    p_fill.add_argument("--notes", default=None)
    p_fill.set_defaults(func=cmd_fill)

    p_val = sub.add_parser("validate-result",
                           help="Validate result.json against the contract.")
    p_val.add_argument("--case", required=True)
    p_val.add_argument("--result", required=True)
    p_val.set_defaults(func=cmd_validate)

    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
