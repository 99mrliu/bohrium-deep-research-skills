#!/usr/bin/env python3
"""Challenge runtime: early result, bbox geometry, then reviewed bindings.

Default invocation reads /input and writes /app/work and /app/output.  The first
run intentionally leaves fields unfinished.  Inspect geometry and rerun with
--bindings to submit semantic decisions without automatic answer promotion.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

from answer_forge import apply_bindings, binding_template
from forge_common import (atomic_write_text, base_result, load_json, target_field_ids,
                          utc_now, validate_result, write_json)
from layout_forge import DEFAULT_LABEL, build_layout, save_layout

FALLBACK = ("pdftotext was unavailable or failed. Install Poppler or provide bbox-layout XHTML; "
            "equivalent command: pdftotext -bbox-layout DOCUMENT.pdf DOCUMENT.bbox.xhtml. "
            "Do not substitute flattened plain text for coordinate geometry.")


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_validated(path, payload, field_ids):
    validate_result(payload, field_ids)
    write_json(path, payload)


def input_error(output_dir, case_id, message, label=None):
    payload = base_result(case_id, [], label=label)
    payload["status"] = "input_error"
    payload["result"]["error"] = message
    payload["uncertainties"] = [{"kind": "input_error", "field_id": None, "message": message}]
    payload["change_records"].append({"event": "input_error", "at": utc_now(), "detail": message})
    write_validated(Path(output_dir) / "result.json", payload, [])
    return payload


def source_discovery(input_dir):
    pdfs = sorted(path for path in input_dir.rglob("*") if path.is_file() and path.suffix.lower() == ".pdf")
    bbox_files = sorted(path for path in input_dir.rglob("*") if path.is_file() and (
        path.suffix.lower() == ".xhtml" or
        (path.suffix.lower() == ".xml" and "bbox" in path.name.lower())))
    return pdfs, bbox_files


def run_pdftotext(pdf, output_path, timeout):
    executable = shutil.which("pdftotext")
    if executable is None:
        return None, "not_installed"
    try:
        completed = subprocess.run(
            [executable, "-bbox-layout", str(pdf), str(output_path)],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=timeout,
            check=False)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return None, "failed: " + str(exc)
    if completed.returncode != 0 or not output_path.exists():
        return None, "failed (exit %d): %s" % (completed.returncode, completed.stderr.strip()[:1000])
    return output_path, "bbox-layout XHTML generated by pdftotext"


def copy_previews(work_dir, output_dir):
    for name in ("table-preview.md", "table-preview.svg"):
        source = Path(work_dir) / name
        if source.exists():
            atomic_write_text(Path(output_dir) / name, source.read_text(encoding="utf-8"))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", default="/input")
    parser.add_argument("--work-dir", default="/app/work")
    parser.add_argument("--output-dir", default="/app/output")
    parser.add_argument("--bindings", help="reviewed JSON bindings; omitted on the geometry-only first pass")
    parser.add_argument("--pdf-timeout", type=int, default=180)
    args = parser.parse_args(argv)
    input_dir = Path(args.input_dir)
    work_dir = Path(args.work_dir)
    output_dir = Path(args.output_dir)
    work_dir.mkdir(parents=True, exist_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)

    case = None
    case_id = "INPUT_ERROR"
    label = None
    try:
        case_path = input_dir / "case.json"
        target_path = input_dir / "target-fields.json"
        task_path = input_dir / "task.md"
        case = load_json(case_path)
        if not isinstance(case, dict) or not isinstance(case.get("case_id"), str) or not case["case_id"]:
            raise ValueError("case.json must contain a non-empty case_id")
        case_id = case["case_id"]
        label = case.get("example_label")
        field_ids = target_field_ids(load_json(target_path))
        task_text = task_path.read_text(encoding="utf-8")
        if not task_text.strip():
            raise ValueError("task.md is empty")
        atomic_write_text(work_dir / "task.md", task_text)
    except Exception as exc:
        input_error(output_dir, case_id, "Input setup failed: %s" % exc, label)
        print("Input setup failed: %s" % exc, file=sys.stderr)
        return 2

    # Contract-safe output exists before source enumeration or any external tool.
    payload = base_result(case_id, field_ids, case.get("output_contract"), label)
    payload["sources"] = [{"source_id": "task-card", "kind": "task",
                           "path": "task.md", "note": "Task instructions are not scientific evidence."}]
    write_validated(output_dir / "result.json", payload, field_ids)
    write_json(work_dir / "reviewed-bindings.template.json", binding_template(payload, label))

    pdfs, supplied_bbox = source_discovery(input_dir)
    geometry_inputs = []
    extraction_messages = []
    for index, path in enumerate(pdfs, 1):
        source_id = "source-%03d" % index
        relative = str(path.relative_to(input_dir))
        source = {"source_id": source_id, "kind": "pdf", "path": relative,
                  "sha256": sha256(path), "bytes": path.stat().st_size}
        destination = work_dir / (source_id + ".bbox.xhtml")
        generated, detail = run_pdftotext(path, destination, max(1, args.pdf_timeout))
        source["bbox_status"] = detail
        payload["sources"].append(source)
        if generated:
            geometry_inputs.append((source_id, generated))
        else:
            extraction_messages.append({"kind": "coordinate_extraction_failed",
                                        "field_id": None, "source_id": source_id,
                                        "message": detail + ". " + FALLBACK})
    for index, path in enumerate(supplied_bbox, 1):
        source_id = "supplied-bbox-%03d" % index
        relative = str(path.relative_to(input_dir))
        payload["sources"].append({
            "source_id": source_id, "kind": "bbox_xhtml", "path": relative,
            "sha256": sha256(path), "bytes": path.stat().st_size,
            "bbox_status": "Supplied bbox XHTML used directly; no text-layer flattening.",
        })
        geometry_inputs.append((source_id, path))
    payload["uncertainties"] = list(extraction_messages)
    if not pdfs and not supplied_bbox:
        payload["uncertainties"].append({
            "kind": "source_missing", "field_id": None,
            "message": "No PDF or supplied bbox XHTML was found under the input directory.",
        })
    write_validated(output_dir / "result.json", payload, field_ids)

    table_document = {"schema_version": "table-coordinate-forge/tables-v1",
                      "label": label or DEFAULT_LABEL,
                      "created_at": utc_now(), "tables": [],
                      "promotion_policy": "Candidates only; reviewed binding required."}
    layout = {"schema_version": "table-coordinate-forge/layout-v1",
              "label": label or DEFAULT_LABEL, "created_at": utc_now(),
              "pages": [], "coordinate_convention": "PDF points as supplied by pdftotext; origin at upper-left"}
    try:
        if geometry_inputs:
            layout, table_document = build_layout(geometry_inputs, label or DEFAULT_LABEL)
        save_layout(layout, table_document, work_dir)
        copy_previews(work_dir, output_dir)
        payload["result"]["layout"] = {
            "usable": bool(table_document["tables"]),
            "table_count": len(table_document["tables"]),
            "segment_count": sum(len(table["segments"]) for table in table_document["tables"]),
            "preview_markdown": "table-preview.md", "preview_svg": "table-preview.svg",
            "binding_policy": "Candidates only; explicit semantic cell binding required.",
        }
        for field in payload["result"]["fields"]:
            if table_document["tables"]:
                field["notes"] = "Coordinate candidates are available; awaiting explicit reviewed cell and condition binding."
            else:
                field["notes"] = "No usable candidate table was reconstructed; inspect source coordinates or extend geometry before binding."
        if not table_document["tables"]:
            payload["uncertainties"].append({
                "kind": "no_table_candidate", "field_id": None,
                "message": "No repeated-gutter table candidate was reconstructed. Inspect page coordinates manually or supply better bbox extraction.",
            })
        else:
            payload["uncertainties"].append({
                "kind": "review_required", "field_id": None,
                "message": "Geometry is a candidate layer. Bind each requested field only after checking row, column, continuation and condition headers against the PDF.",
            })
        payload["change_records"].append({
            "event": "coordinate_geometry_reconstructed", "at": utc_now(),
            "detail": "Parsed %d pages and proposed %d table segments; no field was auto-promoted." % (
                len(layout["pages"]), payload["result"]["layout"]["segment_count"]),
        })
        write_validated(output_dir / "result.json", payload, field_ids)
        write_json(work_dir / "reviewed-bindings.template.json", binding_template(payload, label))
    except Exception as exc:
        message = "Coordinate reconstruction failed: %s. %s" % (exc, FALLBACK)
        payload["uncertainties"].append({"kind": "coordinate_extraction_failed",
                                         "field_id": None, "message": message})
        payload["change_records"].append({"event": "coordinate_extraction_failed",
                                          "at": utc_now(), "detail": message})
        write_validated(output_dir / "result.json", payload, field_ids)
        print(message, file=sys.stderr)
        return 2

    if not args.bindings:
        write_validated(output_dir / "result.json", payload, field_ids)
        print(json.dumps({"status": payload["status"],
                          "result": str(output_dir / "result.json"),
                          "next": "Inspect previews, author reviewed bindings, then rerun with --bindings."}))
        return 0

    try:
        reviewed = load_json(args.bindings)
        staged = apply_bindings(payload, table_document, reviewed, field_ids)
        # Preserve source-level failures alongside field-level binding outcomes.
        existing = {(item.get("kind"), item.get("field_id"), item.get("message"))
                    for item in staged["uncertainties"]}
        for item in extraction_messages:
            key = (item.get("kind"), item.get("field_id"), item.get("message"))
            if key not in existing:
                staged["uncertainties"].append(item)
        validate_result(staged, field_ids)
        write_json(output_dir / "result.json", staged)
        payload = staged
    except Exception as exc:
        message = "Reviewed bindings rejected; no candidate answer was promoted: %s" % exc
        payload["uncertainties"].append({"kind": "binding_rejected", "field_id": None,
                                         "message": message})
        payload["change_records"].append({"event": "reviewed_bindings_rejected",
                                          "at": utc_now(), "detail": message})
        write_validated(output_dir / "result.json", payload, field_ids)
        print(message, file=sys.stderr)
        return 2
    print(json.dumps({"status": payload["status"],
                      "fields": len(payload["result"]["fields"]),
                      "reported": sum(row["status"] == "reported" for row in payload["result"]["fields"]),
                      "result": str(output_dir / "result.json")}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
