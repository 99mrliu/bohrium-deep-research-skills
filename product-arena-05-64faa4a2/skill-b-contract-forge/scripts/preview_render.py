#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""preview_render.py — 把 chapter.md 渲染为自包含 SVG 预览（纯标准库）。

支持：标题层级（#~####）、段落、无序/有序列表、管道表格、代码围栏、引用块、
水平线。中文等全角字符按 2 单位宽度估算换行。输出确定性、无第三方依赖。

用法：
    python3 preview_render.py --chapter /app/output/chapter.md \
        --output /app/output/chapter.preview.svg
"""
import argparse
import html
import os
import re
import sys

PAGE_W = 794          # A4 纵向 96dpi 像素宽
MARGIN = 56
LINE_H = 22
CONTENT_UNITS = 72    # 正文行宽（半角单位）
STYLE = {
    "h1": {"size": 24, "weight": "bold", "color": "#1a1a2e", "before": 26, "after": 12},
    "h2": {"size": 19, "weight": "bold", "color": "#16213e", "before": 20, "after": 10},
    "h3": {"size": 16, "weight": "bold", "color": "#0f3460", "before": 16, "after": 8},
    "h4": {"size": 14, "weight": "bold", "color": "#333333", "before": 12, "after": 6},
    "p":  {"size": 12, "weight": "normal", "color": "#222222", "before": 2, "after": 6},
    "li": {"size": 12, "weight": "normal", "color": "#222222", "before": 0, "after": 2},
    "quote": {"size": 12, "weight": "normal", "color": "#555555", "before": 4, "after": 6},
    "code": {"size": 11, "weight": "normal", "color": "#7a2e0e", "before": 6, "after": 6},
    "tbl": {"size": 11, "weight": "normal", "color": "#222222", "before": 6, "after": 8},
}


def char_width(ch):
    """全角字符（含 CJK）按 2 单位，其余 1 单位。"""
    o = ord(ch)
    if (0x1100 <= o <= 0x115F or 0x2E80 <= o <= 0xA4CF or 0xAC00 <= o <= 0xD7A3
            or 0xF900 <= o <= 0xFAFF or 0xFE30 <= o <= 0xFE4F or 0xFF00 <= o <= 0xFF60
            or 0xFFE0 <= o <= 0xFFE6 or 0x20000 <= o <= 0x2FFFD or 0x30000 <= o <= 0x3FFFD):
        return 2
    return 1


def text_width(s):
    return sum(char_width(c) for c in s)


def wrap_text(text, max_units):
    """按显示宽度换行；优先在空白/标点处断行。确定性。"""
    lines, cur, cur_w = [], "", 0
    for ch in text:
        w = char_width(ch)
        if cur_w + w > max_units and cur:
            lines.append(cur)
            cur, cur_w = ("" if ch == " " else ch), (0 if ch == " " else w)
        else:
            cur += ch
            cur_w += w
    if cur or not lines:
        lines.append(cur)
    return lines


def esc(s):
    return html.escape(s, quote=True)


class Canvas:
    def __init__(self):
        self.y = MARGIN
        self.parts = []

    def text(self, x, y, s, style, extra=""):
        st = STYLE[style]
        self.parts.append(
            '<text x="%d" y="%d" font-size="%d" font-weight="%s" fill="%s" %s>%s</text>'
            % (x, y, st["size"], st["weight"], st["color"], extra, esc(s)))

    def rect(self, x, y, w, h, fill, stroke="none", sw=0):
        self.parts.append('<rect x="%d" y="%d" width="%d" height="%d" fill="%s" stroke="%s" stroke-width="%d"/>'
                          % (x, y, w, h, fill, stroke, sw))

    def line(self, x1, y1, x2, y2, color="#cccccc", sw=1):
        self.parts.append('<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="%s" stroke-width="%d"/>'
                          % (x1, y1, x2, y2, color, sw))

    def gap(self, n):
        self.y += n

    def render(self, title):
        h = self.y + MARGIN
        head = ('<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" '
                'viewBox="0 0 %d %d" font-family="Helvetica, Arial, sans-serif">'
                % (PAGE_W, h, PAGE_W, h))
        bg = '<rect x="0" y="0" width="%d" height="%d" fill="#ffffff"/>' % (PAGE_W, h)
        comment = "<!-- preview of %s | generated by preview_render.py (stdlib only) -->" % esc(title)
        return "\n".join([head, comment, bg] + self.parts + ["</svg>", ""])


def is_table_sep(line):
    return bool(re.match(r"^\s*\|?[\s:|-]+\|?\s*$", line)) and "-" in line


def split_row(line):
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in line.split("|")]


def render_table(cv, rows):
    """rows[0] 为表头；其余为数据行。"""
    cv.gap(STYLE["tbl"]["before"])
    ncols = max(len(r) for r in rows)
    col_w = (PAGE_W - 2 * MARGIN) // max(ncols, 1)
    row_h = 20
    for ri, row in enumerate(rows):
        top = cv.y
        if ri == 0:
            cv.rect(MARGIN, top - 14, col_w * ncols, row_h, "#eef2f7", "#cccccc", 1)
        for ci in range(ncols):
            x = MARGIN + ci * col_w
            cv.rect(x, top - 14, col_w, row_h, "none", "#cccccc", 1)
            cell = row[ci] if ci < len(row) else ""
            maxu = max(int(col_w / 6.2) - 1, 4)
            if text_width(cell) > maxu:
                cell_lines = wrap_text(cell, maxu)
                cell = cell_lines[0][:-1] + "…" if cell_lines[0] else "…"
            weight = 'font-weight="bold"' if ri == 0 else ""
            cv.parts.append(
                '<text x="%d" y="%d" font-size="%d" fill="%s" %s>%s</text>'
                % (x + 4, top + 1, STYLE["tbl"]["size"], STYLE["tbl"]["color"], weight, esc(cell)))
        cv.y += row_h
    cv.gap(STYLE["tbl"]["after"])


def render_paragraph(cv, text, style="p", indent=0, prefix=""):
    st = STYLE[style]
    cv.gap(st["before"])
    for ln in wrap_text(prefix + text, CONTENT_UNITS - indent):
        cv.text(MARGIN + indent * 8, cv.y, ln, style)
        cv.y += LINE_H
    cv.gap(st["after"])


def md_to_svg(md_text, title="chapter.md"):
    cv = Canvas()
    lines = md_text.splitlines()
    i = 0
    in_code = False
    para_buf = []

    def flush_para():
        if para_buf:
            render_paragraph(cv, " ".join(s.strip() for s in para_buf if s.strip()), "p")
            para_buf.clear()

    while i < len(lines):
        line = lines[i]
        if line.strip().startswith("```"):
            flush_para()
            in_code = not in_code
            if in_code:
                cv.gap(STYLE["code"]["before"])
                start_y = cv.y
            else:
                # 背景 rect 需画在代码文字下方：插到该代码块第一个文本元素之前
                bg = '<rect x="%d" y="%d" width="%d" height="%d" fill="#f6f4f0" stroke="#e0dcd4" stroke-width="1"/>' % (
                    MARGIN - 8, start_y - 14, PAGE_W - 2 * MARGIN + 16, cv.y - start_y + 4)
                j = len(cv.parts)
                while j > 0:
                    m2 = re.search(r'y="(\d+)"', cv.parts[j - 1])
                    if m2 and int(m2.group(1)) < start_y:
                        break
                    j -= 1
                cv.parts.insert(j, bg)
                cv.gap(STYLE["code"]["after"])
            i += 1
            continue
        if in_code:
            cv.text(MARGIN, cv.y, line.rstrip()[:CONTENT_UNITS + 8], "code")
            cv.y += LINE_H - 4
            i += 1
            continue
        s = line.strip()
        if not s:
            flush_para()
            i += 1
            continue
        if is_table_sep(s) and para_buf:
            # 表格：para_buf 最后一行是表头
            flush_para()
            i += 1
            continue
        m = re.match(r"^(#{1,4})\s+(.*)$", s)
        if m:
            flush_para()
            style = "h%d" % len(m.group(1))
            st = STYLE[style]
            cv.gap(st["before"])
            for ln in wrap_text(m.group(2).strip(), int(CONTENT_UNITS * 12 / st["size"])):
                cv.text(MARGIN, cv.y, ln, style)
                cv.y += int(LINE_H * st["size"] / 12)
            if len(m.group(1)) == 1:
                cv.line(MARGIN, cv.y - 12, PAGE_W - MARGIN, cv.y - 12, "#1a1a2e", 1)
            cv.gap(st["after"])
            i += 1
            continue
        if re.match(r"^\|.*\|?\s*$", s) and "|" in s:
            flush_para()
            rows = [split_row(s)]
            i += 1
            while i < len(lines) and "|" in lines[i] and lines[i].strip():
                if not is_table_sep(lines[i]):
                    rows.append(split_row(lines[i]))
                i += 1
            render_table(cv, rows)
            continue
        m = re.match(r"^[-*+]\s+(.*)$", s)
        if m:
            flush_para()
            render_paragraph(cv, m.group(1), "li", indent=2, prefix="• ")
            i += 1
            continue
        m = re.match(r"^(\d+)[.)]\s+(.*)$", s)
        if m:
            flush_para()
            render_paragraph(cv, m.group(2), "li", indent=2, prefix="%s. " % m.group(1))
            i += 1
            continue
        m = re.match(r"^>\s?(.*)$", s)
        if m:
            flush_para()
            render_paragraph(cv, m.group(1), "quote", indent=1, prefix="▎")
            i += 1
            continue
        if re.match(r"^(-{3,}|\*{3,}|_{3,})$", s):
            flush_para()
            cv.gap(8)
            cv.line(MARGIN, cv.y, PAGE_W - MARGIN, cv.y, "#999999", 1)
            cv.gap(8)
            i += 1
            continue
        # 表格首行（无前置竖线但下一行是分隔行）也支持
        if ("|" in s and i + 1 < len(lines) and is_table_sep(lines[i + 1])):
            flush_para()
            rows = [split_row(s)]
            i += 2
            while i < len(lines) and "|" in lines[i] and lines[i].strip():
                if not is_table_sep(lines[i]):
                    rows.append(split_row(lines[i]))
                i += 1
            render_table(cv, rows)
            continue
        para_buf.append(s)
        i += 1
    flush_para()
    return cv.render(title)


def main(argv=None):
    ap = argparse.ArgumentParser(description="chapter.md → 自包含 SVG 预览")
    ap.add_argument("--chapter", required=True)
    ap.add_argument("--output", required=True)
    args = ap.parse_args(argv)

    try:
        with open(args.chapter, "r", encoding="utf-8") as f:
            md = f.read()
    except OSError as e:
        print("ERROR: 无法读取 %s：%s" % (args.chapter, e), file=sys.stderr)
        return 2
    try:
        svg = md_to_svg(md, title=os.path.basename(args.chapter))
    except Exception as e:  # 绝不交付伪造预览：失败时输出带原因注释的最小合法 SVG
        svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="794" height="200">'
               "<!-- render failed: %s -->"
               '<text x="40" y="60" font-size="14" fill="#a00">预览渲染失败：%s</text>'
               "</svg>\n" % (esc(str(e)), esc(str(e)[:120])))
        print("WARN: 渲染失败，输出降级 SVG：%s" % e, file=sys.stderr)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(svg)
    n_text = svg.count("<text")
    print("OK: %s（%d 个文本元素，%d 字节）" % (args.output, n_text, len(svg.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
