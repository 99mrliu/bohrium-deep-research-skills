def write_pdf(path: str) -> None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from matplotlib.backends.backend_pdf import PdfPages
    except ImportError:
        print("ERROR: matplotlib is required to build the synthetic PDF", file=sys.stderr)
        sys.exit(2)

    def text_page(pdf, lines):
        fig = plt.figure(figsize=(11, 8.5))
        fig.patch.set_facecolor("white")
        y = 0.95
        for line in lines:
            fig.text(0.06, y, line, fontsize=9, family="monospace", va="top")
            y -= 0.034
        pdf.savefig(fig)
        plt.close(fig)

    with PdfPages(path) as pdf:
        text_page(pdf, PAGE1)
        text_page(pdf, PAGE2)
        # Page 3: 一张简单图 + Figure 1 caption
        fig, ax = plt.subplots(figsize=(11, 8.5))
        xs = [300, 250, 200, 150, 120, 100, 80, 60, 50, 42.3, 35, 20, 10]
        ys = [1.80, 1.72, 1.60, 1.44, 1.28, 1.12, 0.95, 0.70, 0.55, 0.46, 0.42, 0.40, 0.39]
        ax.plot(xs, ys, "o-", color="#1f5fa8")
        ax.axvline(42.3, color="gray", ls="--", lw=1)
        ax.text(45, 1.6, "fictional gap at 42.3 K", fontsize=9, color="gray")
        ax.set_xlabel("Temperature (K)")
        ax.set_ylabel("Thermal conductivity (W/(m·K))")
        ax.set_title("Synthetic cooling curve of fictional QX-7 (fabricated data)")
        ax.invert_xaxis()
        ax.grid(alpha=0.3)
        fig.text(0.08, 0.055, PAGE3_CAPTION, fontsize=9, family="monospace", wrap=True)
        pdf.savefig(fig)
        plt.close(fig)
        text_page(pdf, PAGE4)
        text_page(pdf, PAGE5)


def write_template(path: str) -> bool:
    try:
        from pptx import Presentation
        from pptx.util import Inches, Pt
    except ImportError:
        print("WARN: python-pptx missing; target-template.pptx skipped", file=sys.stderr)
        return False
    prs = Presentation()
    slide = prs.slides.add_slide(prs.slide_layouts[1])  # Title and Content
    slide.shapes.title.text = "Fictional Template — replace this title"
    body = slide.placeholders[1]
    body.text = "Fictional content placeholder"
    for ph in slide.placeholders:
        try:
            ph.text_frame.paragraphs[0].font.size = Pt(24)
        except Exception:
            pass
    _ = Inches  # keep import meaningful for future edits
    prs.save(path)
    return True


def write_csv(path: str) -> None:
    rows = [
        ["batch", "temp_C", "time_h", "yield_pct", "kappa_50K_W_mK"],
        ["S1", 350, 6, 88, 0.55],
        ["S2", 400, 4, 76, 0.61],
        ["S3", 300, 8, 91, 0.42],
    ]
    with open(path, "w", newline="", encoding="utf-8") as f:
        csv.writer(f).writerows(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate a fully fictional synthetic case.")
    ap.add_argument("--out", required=True, help="output input/ directory")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    write_pdf(os.path.join(args.out, "paper.pdf"))
    write_template(os.path.join(args.out, "target-template.pptx"))
    write_csv(os.path.join(args.out, "data.csv"))
    with open(os.path.join(args.out, "case.json"), "w", encoding="utf-8") as f:
        json.dump(CASE_JSON, f, ensure_ascii=False, indent=2)
    with open(os.path.join(args.out, "task.md"), "w", encoding="utf-8") as f:
        f.write(TASK_MD)
    print(f"synthetic case written to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
