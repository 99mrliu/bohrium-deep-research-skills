#!/usr/bin/env python3
"""Incremental requirement/evidence coverage and output-contract checks.

This tool audits records and renders deliverables. It never executes candidate
commands and never decides whether scientific evidence semantically supports a
claim. All writes are atomic replacements in the selected work directory.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import html
import json
import os
from pathlib import Path
import re
import sys
import tempfile
from typing import Any

KINDS = {
    "paper", "environment", "parameter", "run", "comparison",
    "attribution", "artifact",
}
# Standard result fields are generated by the tool. If an input contract also
# declares them, they are satisfied here rather than treated as answer records.
STANDARD_FIELDS = {
    "case_id", "status", "sources", "uncertainty", "change_records", "delivery",
}
RESERVED = {"output_contract"}
STATUS_BY_SCIENCE = {"complete": "success", "degraded": "partial", "unavailable": "unable"}
RESULT_STATUSES = {"success", "partial", "unable", "refused"}
PLACEHOLDERS = {
    "", "n/a", "na", "none", "null", "unknown", "unavailable", "todo", "tbd",
    "placeholder", "no data", "not available", "待定", "未知", "无", "暂无",
    "占位", "待补充", "不可用",
}
SCIENCE_RANK = {"unavailable": 0, "degraded": 1, "complete": 2}


class UserError(Exception):
    pass


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat()


def load_json(path: Path) -> Any:
    try:
        with path.open("r", encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, json.JSONDecodeError) as exc:
        raise UserError(f"cannot read JSON {path}: {exc}") from exc


def nonempty_string(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def generic_fragment(value: str) -> bool:
    normalized = value.strip().lower()
    return normalized in PLACEHOLDERS or bool(re.match(
        r"^(todo|tbd|placeholder|n/a|not available|no data)\b", normalized
    )) or normalized.startswith(("待补充", "待定", "占位"))


def locator_nonempty(value: Any) -> bool:
    if isinstance(value, str):
        return bool(value.strip())
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return True  # Page, line, table, and figure numbers may be numeric.
    if isinstance(value, list):
        return bool(value) and all(locator_nonempty(item) for item in value)
    if isinstance(value, dict):
        return bool(value) and all(
            nonempty_string(str(key)) and locator_nonempty(item)
            for key, item in value.items()
        )
    return False


def parse_field_list(items: Any) -> list[str]:
    if isinstance(items, dict):
        # A field mapping declares every top-level key unless explicitly optional.
        return [str(key) for key, spec in items.items()
                if not (isinstance(spec, dict) and spec.get("required") is False)]
    if not isinstance(items, list):
        raise UserError("output_contract fields must be a list or mapping")
    fields: list[str] = []
    for item in items:
        if isinstance(item, str):
            name = item
        elif isinstance(item, dict):
            if item.get("required") is False:
                continue
            name = next((item[key] for key in ("name", "field", "key", "id")
                         if key in item), None)
        else:
            name = None
        if not nonempty_string(name):
            raise UserError(f"invalid output_contract field entry: {item!r}")
        fields.append(name.strip())
    return fields


def extract_fields(contract: Any) -> list[str]:
    """Extract all declared top-level required fields from common contract shapes."""
    if isinstance(contract, list):
        fields = parse_field_list(contract)
    elif isinstance(contract, dict):
        if "output_contract" in contract and len(contract) == 1:
            return extract_fields(contract["output_contract"])
        if "properties" in contract:
            properties = contract["properties"]
            if not isinstance(properties, dict):
                raise UserError("JSON Schema properties must be an object")
            if "required" in contract:
                required = contract["required"]
                if not isinstance(required, list) or not all(
                        nonempty_string(item) for item in required):
                    raise UserError("JSON Schema required must be a string list")
                # Preserve declaration order and retain required names omitted from properties.
                fields = [name for name in properties if name in required]
                fields += [name for name in required if name not in fields]
            else:
                # In a delivery contract, undeclared optional semantics are unsafe:
                # treat every declared top-level property as required.
                fields = list(properties)
        elif "fields" in contract:
            fields = parse_field_list(contract["fields"])
        elif "required_fields" in contract:
            fields = parse_field_list(contract["required_fields"])
        elif "required" in contract and isinstance(contract["required"], list):
            fields = parse_field_list(contract["required"])
        else:
            # Direct mapping: {"field_name": {"type": ...}, ...}.
            fields = parse_field_list(contract)
    else:
        raise UserError("output_contract must be a list, object, or JSON Schema object")
    if not fields:
        raise UserError("output_contract declares no required fields")
    duplicates = sorted({name for name in fields if fields.count(name) > 1})
    if duplicates:
        raise UserError(f"duplicate contract fields: {duplicates}")
    reserved = sorted(RESERVED.intersection(fields))
    if reserved:
        raise UserError(f"contract fields use reserved result names: {reserved}")
    # A user contract may explicitly require any standard result field. Those
    # fields are emitted by make_result and must not also become answer records.
    return [name for name in fields if name not in STANDARD_FIELDS]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    try:
        with path.open("rb") as handle:
            for block in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(block)
    except OSError as exc:
        raise UserError(f"cannot hash evidence {path}: {exc}") from exc
    return digest.hexdigest()


def atomic_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def dump_json(path: Path, value: Any) -> None:
    atomic_text(path, json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def validate_fragment(value: Any, trail: str) -> list[str]:
    errors: list[str] = []
    if value is None:
        return [f"{trail}: null fragment"]
    if isinstance(value, str):
        if generic_fragment(value):
            errors.append(f"{trail}: empty, generic, or placeholder string")
    elif isinstance(value, (list, dict)):
        if not value:
            errors.append(f"{trail}: empty container")
        elif isinstance(value, list):
            for index, item in enumerate(value):
                errors.extend(validate_fragment(item, f"{trail}[{index}]"))
        else:
            for key, item in value.items():
                errors.extend(validate_fragment(item, f"{trail}.{key}"))
    elif not isinstance(value, (int, float, bool)):
        errors.append(f"{trail}: unsupported fragment type")
    return errors


def diagnostics(state: dict[str, Any]) -> dict[str, Any]:
    fields = state["contract_fields"]
    evidence = {item["id"]: item for item in state["evidence"]}
    answers = state["answers"]
    requirements = state["requirements"]
    result = {
        "fields_without_answer": [],
        "unavailable_fields": [],
        "fields_without_evidence": [],
        "requirements_without_evidence": [],
        "artifacts_without_evidence": [],
        "evidence_without_fields": [],
        "orphan_evidence": [],
        "invalid_references": [],
    }
    used_evidence: set[str] = set()
    for field in fields:
        record = answers.get(field)
        linked = set()
        if record:
            if "unavailable" in record:
                result["unavailable_fields"].append(field)
            linked.update(record.get("evidence_ids", []))
        for requirement in requirements:
            if field in requirement["fields"]:
                linked.update(requirement["evidence_ids"])
        valid_linked = {
            evidence_id for evidence_id in linked
            if evidence_id in evidence and field in evidence[evidence_id]["fields"]
        }
        if not valid_linked:
            result["fields_without_evidence"].append(field)
        if not record:
            result["fields_without_answer"].append(field)
        if record:
            for evidence_id in record.get("evidence_ids", []):
                used_evidence.add(evidence_id)
                if evidence_id not in evidence:
                    result["invalid_references"].append(
                        f"answer {field}: unknown evidence {evidence_id}")
                elif field not in evidence[evidence_id]["fields"]:
                    result["invalid_references"].append(
                        f"answer {field}: evidence {evidence_id} not tagged for field")
    known_artifacts = {
        artifact for item in evidence.values() for artifact in item["artifacts"]
    }
    for requirement in requirements:
        req_id = requirement["id"]
        valid_req_evidence = set()
        for evidence_id in requirement["evidence_ids"]:
            used_evidence.add(evidence_id)
            if evidence_id not in evidence:
                result["invalid_references"].append(
                    f"requirement {req_id}: unknown evidence {evidence_id}")
            elif not set(requirement["fields"]).intersection(evidence[evidence_id]["fields"]):
                result["invalid_references"].append(
                    f"requirement {req_id}: evidence {evidence_id} shares no field")
            else:
                valid_req_evidence.add(evidence_id)
        if not valid_req_evidence:
            result["requirements_without_evidence"].append(req_id)
        for artifact in requirement["required_artifacts"]:
            if artifact not in known_artifacts:
                result["artifacts_without_evidence"].append(f"{req_id}:{artifact}")
    for evidence_id, item in evidence.items():
        if not item["fields"]:
            result["evidence_without_fields"].append(evidence_id)
        if evidence_id not in used_evidence or not item["fields"]:
            result["orphan_evidence"].append(evidence_id)
    for key in result:
        result[key] = sorted(set(result[key]))
    return result


def derived_science(state: dict[str, Any], diag: dict[str, Any]) -> str:
    answered = [
        field for field in state["contract_fields"]
        if field in state["answers"] and "answer_fragment" in state["answers"][field]
    ]
    requested = state.get("requested_scientific_status", "complete")
    if requested not in SCIENCE_RANK:
        requested = "degraded"
    if not answered:
        ceiling = "unavailable"
    elif (diag["fields_without_answer"] or diag["unavailable_fields"]
          or diag["fields_without_evidence"] or diag["requirements_without_evidence"]
          or diag["artifacts_without_evidence"] or diag["invalid_references"]
          or diag["orphan_evidence"]):
        ceiling = "degraded"
    else:
        ceiling = "complete"
    return min((requested, ceiling), key=lambda value: SCIENCE_RANK[value])


def coverage_complete(state: dict[str, Any], diag: dict[str, Any]) -> bool:
    missing_keys = [key for key in diag if diag[key]]
    return bool(state.get("finalized")) and not missing_keys


def validate_evidence_current(state: dict[str, Any]) -> list[str]:
    errors = []
    for record in state["evidence"]:
        path = Path(record["path"])
        if not path.is_file():
            errors.append(f"evidence {record['id']}: file missing: {path}")
        elif sha256(path) != record["sha256"]:
            errors.append(f"evidence {record['id']}: SHA256 changed: {path}")
        if not locator_nonempty(record["locator"]):
            errors.append(f"evidence {record['id']}: locator is empty")
        if record["kind"] not in KINDS:
            errors.append(f"evidence {record['id']}: invalid kind")
    return errors


def result_sources(state: dict[str, Any]) -> list[dict[str, Any]]:
    """Expose only registered, hashed evidence as top-level source records."""
    return [{
        "id": item["id"],
        "path": item["path"],
        "hash": item["sha256"],
        "locator": item["locator"],
        "kind": item["kind"],
    } for item in state["evidence"]]


def result_uncertainty(state: dict[str, Any], diag: dict[str, Any]) -> dict[str, Any]:
    unavailable_reasons = []
    for field in state["contract_fields"]:
        record = state["answers"].get(field, {})
        if "unavailable" in record:
            unavailable_reasons.append({"field": field, **record["unavailable"]})
    return {
        "scientific_notes": state.get("scientific_notes", []),
        "unavailable_reasons": unavailable_reasons,
        "coverage_gaps": diag,
    }


def validate_result(state: dict[str, Any], result: dict[str, Any],
                    diag: dict[str, Any]) -> list[str]:
    errors = validate_evidence_current(state)
    expected = {*STANDARD_FIELDS, *state["contract_fields"]}
    missing = sorted(expected - set(result))
    extra = sorted(set(result) - expected)
    if missing:
        errors.append(f"result missing top-level keys: {missing}")
    if extra:
        errors.append(f"result unexpected top-level keys: {extra}")
    if result.get("case_id") != state["case_id"]:
        errors.append("case_id does not match case")
    science_status = derived_science(state, diag)
    expected_status = STATUS_BY_SCIENCE[science_status]
    actual_status = result.get("status")
    if not isinstance(actual_status, str) or actual_status not in RESULT_STATUSES \
            or actual_status != expected_status:
        errors.append(f"status must match scientific status {science_status}: {expected_status}")
    if result.get("sources") != result_sources(state):
        errors.append("sources must exactly reflect registered evidence path/hash/locator/kind records")
    if result.get("uncertainty") != result_uncertainty(state, diag):
        errors.append("uncertainty must contain current scientific notes, unavailable reasons, and coverage gaps")
    records = result.get("change_records")
    valid_records = isinstance(records, list)
    if valid_records:
        valid_records = all(
            isinstance(record, dict)
            and record.get("operation") in {"init", "register", "finalize"}
            and record.get("sequence") == index
            and isinstance(record.get("atomic_state"), dict)
            for index, record in enumerate(records, 1))
    if not valid_records or records != state.get("change_records", []):
        errors.append("change_records must equal sequential init/register/finalize atomic state records")
    evidence = {item["id"]: item for item in state["evidence"]}
    for field in state["contract_fields"]:
        record = result.get(field)
        if not isinstance(record, dict):
            errors.append(f"{field}: field record must be an object")
            continue
        has_answer = "answer_fragment" in record
        has_unavailable = "unavailable" in record
        if has_answer == has_unavailable:
            errors.append(f"{field}: exactly one answer_fragment or unavailable required")
        if has_answer:
            errors.extend(validate_fragment(record["answer_fragment"], field))
            ids = record.get("evidence_ids")
            if not isinstance(ids, list) or not ids:
                errors.append(f"{field}: answered field requires evidence_ids")
                ids = []
            for evidence_id in ids:
                if evidence_id not in evidence:
                    errors.append(f"{field}: unknown evidence {evidence_id}")
                elif field not in evidence[evidence_id]["fields"]:
                    errors.append(f"{field}: evidence {evidence_id} lacks field tag")
        if has_unavailable:
            detail = record["unavailable"]
            if not isinstance(detail, dict):
                errors.append(f"{field}: unavailable must be an object")
            else:
                reason = detail.get("reason")
                if not nonempty_string(reason) or len(reason.strip()) < 8 \
                        or reason.strip().lower() in PLACEHOLDERS:
                    errors.append(f"{field}: unavailable needs a specific reason")
                if not any(detail.get(key) for key in
                           ("missing_materials", "missing_evidence", "next_steps")):
                    errors.append(f"{field}: unavailable needs missing items or next steps")
            for evidence_id in record.get("evidence_ids", []):
                if evidence_id not in evidence:
                    errors.append(f"{field}: unknown evidence {evidence_id}")
    errors.extend(f"coverage: {item}" for item in diag["invalid_references"])
    return sorted(set(errors))


def make_result(state: dict[str, Any], contract_status: str,
                coverage_status: str, science_status: str,
                diag: dict[str, Any], errors: list[str]) -> dict[str, Any]:
    result: dict[str, Any] = {
        "case_id": state["case_id"],
        "status": STATUS_BY_SCIENCE[science_status],
    }
    for field in state["contract_fields"]:
        result[field] = state["answers"].get(field, {
            "answer_fragment": "TODO: register a substantive answer fragment",
            "evidence_ids": [],
            "_draft_placeholder": True,
        })
    result["sources"] = result_sources(state)
    result["uncertainty"] = result_uncertainty(state, diag)
    result["change_records"] = state.get("change_records", [])
    result["delivery"] = {
        "contract_status": contract_status,
        "coverage_status": coverage_status,
        "scientific_status": science_status,
        "scientific_notes": state.get("scientific_notes", []),
        "coverage_diagnostics": diag,
        "contract_errors": errors,
        "generated_at": now(),
        "note": "Contract validity does not imply complete coverage or scientific success.",
    }
    return result


def markdown(state: dict[str, Any], result: dict[str, Any]) -> str:
    delivery = result["delivery"]
    answers = state["answers"]
    evidence = {item["id"]: item for item in state["evidence"]}
    lines = [
        f"# Coverage: {state['case_id']}", "",
        f"- Delivery status: **{result['status']}**",
        f"- Contract: **{delivery['contract_status']}**",
        f"- Coverage: **{delivery['coverage_status']}**",
        f"- Scientific status: **{delivery['scientific_status']}**",
        "- These statuses are independent; PASS is not scientific success.", "",
        "## Field matrix", "",
        "| Field | Answer state | Evidence IDs |", "|---|---|---|",
    ]
    for field in state["contract_fields"]:
        record = answers.get(field)
        if not record:
            status = "missing"
            ids: list[str] = []
        elif "unavailable" in record:
            status = "unavailable (declared)"
            ids = record.get("evidence_ids", [])
        else:
            status = "answer fragment"
            ids = record.get("evidence_ids", [])
        linked = set(ids)
        for requirement in state["requirements"]:
            if field in requirement["fields"]:
                linked.update(requirement["evidence_ids"])
        lines.append(f"| {field} | {status} | {', '.join(sorted(linked)) or 'NONE'} |")
    lines.extend(["", "## Requirements and required artifacts", "",
                  "| Requirement | Question | Fields | Required artifacts | Evidence IDs |",
                  "|---|---|---|---|---|"])
    for req in state["requirements"]:
        lines.append(
            f"| {req['id']} | {req['question'].replace('|', '%7C')} | "
            f"{', '.join(req['fields'])} | {', '.join(req['required_artifacts'])} | "
            f"{', '.join(req['evidence_ids']) or 'NONE'} |")
    lines.extend(["", "## Evidence ledger", "",
                  "| ID | Kind | Locator | File | SHA256 |", "|---|---|---|---|---|"])
    for item in state["evidence"]:
        locator = json.dumps(item["locator"], ensure_ascii=False)
        lines.append(
            f"| {item['id']} | {item['kind']} | {locator.replace('|', '%7C')} | "
            f"{item['path']} | `{item['sha256']}` |")
    lines.extend(["", "## Bidirectional leak checks", ""])
    for key, values in delivery["coverage_diagnostics"].items():
        lines.append(f"- `{key}`: {json.dumps(values, ensure_ascii=False)}")
    if delivery["contract_errors"]:
        lines.extend(["", "## Contract errors", ""])
        lines.extend(f"- {error}" for error in delivery["contract_errors"])
    lines.extend(["", "## Semantic review boundary", "",
                  "A matching `kind`, file hash, and locator prove only that a stable evidence "
                  "record exists. An agent must read the cited source and justify semantic support, "
                  "including assumptions, units, tolerance, candidate failure, and difference attribution.", ""])
    return "\n".join(lines)


