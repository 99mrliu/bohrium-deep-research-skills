def render_png(workdir: Path, state: dict[str, Any], result: dict[str, Any]) -> None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return
    fields = state["contract_fields"]
    answers = state["answers"]
    labels = []
    colors = []
    for field in fields:
        record = answers.get(field)
        labels.append(field)
        colors.append("#c92a2a" if not record else
                      ("#e67700" if "unavailable" in record else "#2b8a3e"))
    fig, ax = plt.subplots(figsize=(11, max(3.5, 1.0 + 0.65 * len(fields))))
    ax.barh(list(reversed(labels)), [1] * len(labels),
            color=list(reversed(colors)), height=0.55)
    ax.set_xlim(0, 1)
    ax.set_xticks([])
    ax.set_xlabel("Green=answer; orange=declared unavailable; red=missing")
    delivery = result["delivery"]
    ax.set_title(f"status {result['status']} | {state['case_id']} | contract {delivery['contract_status']} | "
                 f"coverage {delivery['coverage_status']} | science {delivery['scientific_status']}",
                 fontsize=11)
    for spine in ax.spines.values():
        spine.set_visible(False)
    fig.tight_layout()
    path = workdir / "coverage.png"
    descriptor, temporary = tempfile.mkstemp(prefix=".coverage.", suffix=".png", dir=workdir)
    os.close(descriptor)
    try:
        fig.savefig(temporary, dpi=140)
        os.replace(temporary, path)
    finally:
        plt.close(fig)
        if os.path.exists(temporary):
            os.unlink(temporary)


def append_change_record(state: dict[str, Any], change: dict[str, Any],
                         contract_status: str, coverage_status: str,
                         science_status: str) -> None:
    records = state.setdefault("change_records", [])
    record = {
        "sequence": len(records) + 1,
        "operation": change["operation"],
        "recorded_at": now(),
        "details": change.get("details", {}),
        "atomic_state": {
            "finalized": bool(state.get("finalized")),
            "contract_status": contract_status,
            "coverage_status": coverage_status,
            "scientific_status": science_status,
            "status": STATUS_BY_SCIENCE[science_status],
        },
    }
    records.append(record)


def persist(state: dict[str, Any], workdir: Path, final_errors: list[str] | None = None,
            change: dict[str, Any] | None = None) -> dict[str, Any]:
    diag = diagnostics(state)
    contract_status = state.get("contract_status", "DRAFT")
    if final_errors is not None:
        contract_status = "FAIL" if final_errors else "PASS"
    coverage_status = "complete" if coverage_complete(state, diag) else "partial"
    science_status = derived_science(state, diag)
    state["contract_status"] = contract_status
    state["coverage_status"] = coverage_status
    state["scientific_status"] = science_status
    state["diagnostics"] = diag
    state["updated_at"] = now()
    if change is not None:
        append_change_record(state, change, contract_status, coverage_status, science_status)
    result = make_result(state, contract_status, coverage_status, science_status, diag,
                         final_errors if final_errors is not None else [])
    dump_json(workdir / "result.json", result)
    atomic_text(workdir / "coverage.md", markdown(state, result))
    atomic_text(workdir / "coverage.svg", svg(state, result))
    dump_json(workdir / "coverage.json", state)
    if state.get("render_png"):
        render_png(workdir, state, result)
    return result


def command_init(args: argparse.Namespace) -> int:
    case_path = Path(args.case).expanduser().resolve()
    case = load_json(case_path)
    if not isinstance(case, dict) or "output_contract" not in case:
        raise UserError("case.json must be an object containing output_contract")
    case_id = args.case_id or case.get("case_id")
    if not nonempty_string(case_id):
        raise UserError("case_id is required in case.json or --case-id")
    workdir = Path(args.workdir).expanduser().resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    if (workdir / "coverage.json").exists():
        raise UserError(f"refusing to overwrite existing coverage state in {workdir}")
    state = {
        "schema_version": 2,
        "case_id": case_id,
        "case_path": str(case_path),
        "contract_fields": extract_fields(case["output_contract"]),
        "requirements": [],
        "evidence": [],
        "answers": {},
        "requested_scientific_status": "unavailable",
        "scientific_notes": ["Initialized before evidence and runs; no scientific success implied."],
        "change_records": [],
        "finalized": False,
        "contract_status": "DRAFT",
        "render_png": bool(args.with_png),
        "created_at": now(),
    }
    result = persist(state, workdir, change={
        "operation": "init",
        "details": {"case_id": case_id, "contract_fields": state["contract_fields"]},
    })
    print(f"initialized {case_id}: {len(state['contract_fields'])} required answer fields; "
          f"status {result['status']}; DRAFT/partial/unavailable")
    return 0


def normalize_requirements(payload: Any, fields: list[str]) -> list[dict[str, Any]]:
    records = payload.get("requirements") if isinstance(payload, dict) else payload
    if not isinstance(records, list):
        raise UserError("requirements payload must be a list or {requirements: [...]} object")
    output = []
    for index, record in enumerate(records):
        if not isinstance(record, dict):
            raise UserError(f"requirement {index} is not an object")
        req_id = record.get("id", f"req-{index + 1}")
        question = record.get("question")
        req_fields = record.get("fields")
        artifacts = record.get("required_artifacts", [])
        evidence_ids = record.get("evidence_ids", [])
        if not nonempty_string(req_id) or not nonempty_string(question):
            raise UserError(f"requirement {index} needs nonempty id and task-specific question")
        if not isinstance(req_fields, list) or not req_fields:
            raise UserError(f"requirement {req_id} needs nonempty fields")
        unknown = set(req_fields) - set(fields)
        if unknown:
            raise UserError(f"requirement {req_id} has unknown fields {sorted(unknown)}")
        if not isinstance(artifacts, list) or not all(nonempty_string(x) for x in artifacts):
            raise UserError(f"requirement {req_id} required_artifacts must be strings")
        if not isinstance(evidence_ids, list) or not all(nonempty_string(x) for x in evidence_ids):
            raise UserError(f"requirement {req_id} evidence_ids must be strings")
        output.append({"id": req_id.strip(), "question": question.strip(),
                       "fields": req_fields, "required_artifacts": artifacts,
                       "evidence_ids": evidence_ids})
    return output


def normalize_evidence(payload: Any, fields: list[str], base_dir: Path) -> list[dict[str, Any]]:
    records = payload.get("evidence") if isinstance(payload, dict) else payload
    if not isinstance(records, list):
        raise UserError("evidence payload must be a list or {evidence: [...]} object")
    output = []
    for index, record in enumerate(records):
        if not isinstance(record, dict):
            raise UserError(f"evidence {index} is not an object")
        evidence_id = record.get("id", f"evidence-{index + 1}")
        kind = record.get("kind")
        if not nonempty_string(evidence_id) or kind not in KINDS:
            raise UserError(f"evidence {index} needs id and valid kind {sorted(KINDS)}")
        if not locator_nonempty(record.get("locator")):
            raise UserError(f"evidence {evidence_id} locator must be nonempty at every leaf")
        raw_path = record.get("path")
        if not nonempty_string(raw_path):
            raise UserError(f"evidence {evidence_id} needs a real file path")
        path = Path(raw_path).expanduser()
        if not path.is_absolute():
            path = base_dir / path
        path = path.resolve()
        if not path.is_file():
            raise UserError(f"evidence {evidence_id} is not a file: {path}")
        actual_hash = sha256(path)
        if record.get("sha256") and record["sha256"] != actual_hash:
            raise UserError(f"evidence {evidence_id} supplied SHA256 does not match")
        record_fields = record.get("fields", [])
        artifacts = record.get("artifacts", [])
        if not isinstance(record_fields, list) or set(record_fields) - set(fields):
            raise UserError(f"evidence {evidence_id} fields must be known contract fields")
        if not isinstance(artifacts, list) or not all(nonempty_string(x) for x in artifacts):
            raise UserError(f"evidence {evidence_id} artifacts must be nonempty strings")
        output.append({"id": evidence_id.strip(), "kind": kind, "path": str(path),
                       "sha256": actual_hash, "locator": record["locator"],
                       "fields": record_fields, "artifacts": artifacts,
                       "note": record.get("note", ""),
                       "command": record.get("command", "")})
    return output


def load_state(workdir: Path) -> dict[str, Any]:
    state = load_json(workdir / "coverage.json")
    if not isinstance(state, dict) or "contract_fields" not in state:
        raise UserError(f"no initialized state in {workdir}")
    state.setdefault("change_records", [])
    return state


def command_register(args: argparse.Namespace) -> int:
    workdir = Path(args.workdir).expanduser().resolve()
    state = load_state(workdir)
    if state.get("finalized") and state.get("contract_status") == "PASS":
        raise UserError("PASS state is finalized; initialize a new audit for later revisions")
    if state.get("finalized"):
        # A failed final remains repairable without discarding any partial records.
        state["finalized"] = False
        state["contract_status"] = "DRAFT"
    payload = load_json(Path(args.payload).expanduser().resolve())
    change_details: dict[str, Any] = {"kind": args.kind}
    if args.kind == "requirements":
        records = normalize_requirements(payload, state["contract_fields"])
        known = {item["id"] for item in state["requirements"]}
        if any(item["id"] in known for item in records):
            raise UserError("duplicate requirement id")
        state["requirements"].extend(records)
        change_details["requirement_ids"] = [item["id"] for item in records]
    elif args.kind == "evidence":
        base_dir = Path(args.base_dir).expanduser().resolve() if args.base_dir else workdir
        records = normalize_evidence(payload, state["contract_fields"], base_dir)
        known = {item["id"] for item in state["evidence"]}
        if any(item["id"] in known for item in records):
            raise UserError("duplicate evidence id")
        state["evidence"].extend(records)
        change_details["evidence_ids"] = [item["id"] for item in records]
    else:
        records = payload.get("fields") if isinstance(payload, dict) and "fields" in payload else payload
        if not isinstance(records, dict):
            raise UserError("answers payload must be a field mapping or {fields: {...}} object")
        unknown = set(records) - set(state["contract_fields"])
        if unknown:
            raise UserError(f"answers have unknown fields {sorted(unknown)}")
        for field, record in records.items():
            if not isinstance(record, dict) or not (
                    ("answer_fragment" in record) ^ ("unavailable" in record)):
                raise UserError(f"answer {field} requires exactly one answer_fragment or unavailable")
            if not isinstance(record.get("evidence_ids", []), list):
                raise UserError(f"answer {field} evidence_ids must be a list")
        state["answers"].update(records)
        change_details["fields"] = sorted(records)
        if isinstance(payload, dict):
            if "scientific_status" in payload:
                status = payload["scientific_status"]
                if status not in SCIENCE_RANK:
                    raise UserError("scientific_status must be complete, degraded, or unavailable")
                state["requested_scientific_status"] = status
            if "scientific_notes" in payload:
                notes = payload["scientific_notes"]
                if not isinstance(notes, list) or not all(nonempty_string(note) for note in notes):
                    raise UserError("scientific_notes must be nonempty strings")
                state["scientific_notes"] = notes
    result = persist(state, workdir, change={
        "operation": "register", "details": change_details,
    })
    print(f"registered {args.kind}: status {result['status']}; "
          f"contract {result['delivery']['contract_status']}; "
          f"coverage {result['delivery']['coverage_status']}; scientific {result['delivery']['scientific_status']}")
    return 0


def command_finalize(args: argparse.Namespace) -> int:
    workdir = Path(args.workdir).expanduser().resolve()
    state = load_state(workdir)
    state["finalized"] = True
    state["requested_scientific_status"] = state.get("requested_scientific_status", "degraded")
    # Build once with FINAL pending so result validation checks the exact top-level shape.
    diag = diagnostics(state)
    provisional = make_result(state, "DRAFT", "partial", derived_science(state, diag), diag, [])
    errors = validate_result(state, provisional, diag)
    result = persist(state, workdir, errors, change={
        "operation": "finalize",
        "details": {"contract_errors": errors, "exit_code": 0 if not errors else 2},
    })
    delivery = result["delivery"]
    print(f"STATUS {result['status']}")
    print(f"CONTRACT {delivery['contract_status']}")
    print(f"COVERAGE {delivery['coverage_status']}")
    print(f"SCIENTIFIC {delivery['scientific_status']}")
    for error in errors:
        print(f"ERROR: {error}", file=sys.stderr)
    return 0 if not errors else 2


def parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(description=__doc__)
    commands = root.add_subparsers(dest="command", required=True)
    init = commands.add_parser("init", help="write an honest DRAFT/partial skeleton immediately")
    init.add_argument("--case", required=True)
    init.add_argument("--workdir", required=True)
    init.add_argument("--case-id")
    init.add_argument("--with-png", action="store_true", help="also render PNG when matplotlib exists")
    init.set_defaults(handler=command_init)
    register = commands.add_parser("register", help="incrementally register requirements/evidence/answers")
    register.add_argument("kind", choices=("requirements", "evidence", "answers"))
    register.add_argument("--payload", required=True)
    register.add_argument("--workdir", required=True)
    register.add_argument("--base-dir", help="base for relative evidence paths (evidence only)")
    register.set_defaults(handler=command_register)
    finalize = commands.add_parser("finalize", help="compile result and run strict final checks")
    finalize.add_argument("--workdir", required=True)
    finalize.set_defaults(handler=command_finalize)
    return root


def main(argv: list[str] | None = None) -> int:
    try:
        args = parser().parse_args(argv)
        return int(args.handler(args))
    except UserError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
