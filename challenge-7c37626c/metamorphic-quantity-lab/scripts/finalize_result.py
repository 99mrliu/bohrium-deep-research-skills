#!/usr/bin/env python3
"""Finalize the exact dynamic result contract with agent-authored answers and real artifacts."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from quantity_core import VerificationError
from runtime_contract import base_result, finalize, locate_contract, normalize_contract, read_json


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(value, handle, indent=2, ensure_ascii=False, allow_nan=False)
        handle.write("\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", default="/input/case.json")
    parser.add_argument("--task", default="/input/task.md")
    parser.add_argument("--analysis", default="/app/work/analysis.json")
    parser.add_argument("--answers", required=True, help="JSON written by the agent, never generated by this script")
    parser.add_argument("--artifacts", nargs="+", required=True, help="Existing analysis/report/data/image files")
    parser.add_argument("--output", default="/app/output/result.json")
    args = parser.parse_args(argv)
    case_path, task_path, analysis_path = Path(args.case), Path(args.task), Path(args.analysis)
    output_path = Path(args.output)
    case: dict[str, Any] = {}
    try:
        case = read_json(case_path)
        if not isinstance(case, dict):
            raise VerificationError("case.json must be an object")
        task_text = task_path.read_text(encoding="utf-8")
        contract = normalize_contract(locate_contract(task_text, case))
        analysis = read_json(analysis_path)
        answers = read_json(Path(args.answers))
        if not isinstance(analysis, dict) or analysis.get("case_id") != case.get("case_id"):
            raise VerificationError("analysis case_id is absent or differs from the case")
        artifacts: Any = [str(Path(path).resolve()) for path in args.artifacts]
        definition = contract["fields"].get("artifacts", {"type": "array"})
        kind = definition.get("type") if isinstance(definition, dict) else definition
        if kind in {"object", "dict"}:
            artifacts = {Path(path).name: path for path in artifacts}
        result, errors = finalize(contract, case.get("case_id"), analysis, answers, artifacts)
        if errors:
            error_path = analysis_path.parent / "finalization_errors.json"
            write_json(error_path, {"errors": errors, "status": "partial", "note": "No missing evidence or agent answer was fabricated."})
            # Preserve an honest partial result even when finalization fails.
            partial_analysis = dict(analysis)
            partial_analysis["recommended_status"] = "partial"
            partial = base_result(contract, case.get("case_id"), partial_analysis)
            partial["case_id"] = case.get("case_id")
            write_json(output_path, partial)
            for error in errors:
                print(f"finalization error: {error}", file=sys.stderr)
            print(f"details: {error_path}", file=sys.stderr)
            return 2
        write_json(output_path, result)
        print(json.dumps({"result": str(output_path), "status": result.get("status", result.get("verification_status")), "case_id": result.get("case_id"), "answers": "agent-authored supplied", "artifact_count": len(args.artifacts)}, ensure_ascii=False))
        return 0
    except (VerificationError, OSError, UnicodeError) as exc:
        print(f"finalization failed safely: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
