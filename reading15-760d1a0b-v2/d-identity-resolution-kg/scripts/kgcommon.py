def dump_json(obj, path):
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(obj, fh, ensure_ascii=False, indent=2, sort_keys=True)
        fh.write("\n")


def load_json(path):
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()

# ---------------------------------------------------------------------------
# Normalization keys (casefold, hyphen/space stripping, symbol folding)
# ---------------------------------------------------------------------------

_SUBSCRIPT = str.maketrans("₀₁₂₃₄₅₆₇₈₉", "0123456789")
_DASHES = {"–": "-", "—": "-", "−": "-", "‐": "-", "‑": "-"}
_SYMBOL_FOLD = {
    "α": "alpha", "β": "beta", "γ": "gamma", "δ": "delta",
    "×": "x", "°": "deg",
}


def norm_key(surface):
    """Deterministic normalization key for an entity surface form.

    Steps: unicode subscript folding -> dash folding -> symbol folding ->
    casefold -> drop every non-alphanumeric character (spaces, hyphens,
    apostrophes, commas, parentheses).
    """
    if surface is None:
        return ""
    text = str(surface).translate(_SUBSCRIPT)
    for src, dst in _DASHES.items():
        text = text.replace(src, dst)
    for src, dst in sorted(_SYMBOL_FOLD.items()):
        text = text.replace(src, dst)
    text = text.casefold()
    return "".join(ch for ch in text if ch.isalnum())

# ---------------------------------------------------------------------------
# Text utilities
# ---------------------------------------------------------------------------

_SENT_SPLIT = re.compile(r"(?<=[.!?])\s+")


def sentences(text):
    """Split a paragraph into sentences; each result is an exact substring."""
    return [s for s in _SENT_SPLIT.split(text) if s.strip()]


def sentence_with(text, needle):
    """Return the first sentence of text containing needle (exact substring)."""
    for sent in sentences(text):
        if needle in sent:
            return sent
    return text[:240]

