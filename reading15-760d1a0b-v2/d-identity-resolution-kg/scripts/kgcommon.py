def guess_type(surface):
    """Guess an entity block: material / metric / method / unknown."""
    key = norm_key(surface)
    if key in METRIC_TERMS:
        return "metric"
    if key in METHOD_TERMS:
        return "method"
    has_digit = any(ch.isdigit() for ch in surface)
    n_upper = sum(1 for ch in surface if ch.isupper())
    if has_digit and n_upper >= 1 and surface[:1].isupper():
        return "material"  # formula-like: MAPbI3, TiO2, PbI2
    if "-" in surface and n_upper >= 2:
        return "material"  # hyphenated material names: spiro-OMeTAD, Li-TFSI
    return "unknown"


def block_compatible(block_a, block_b):
    return block_a == block_b or "unknown" in (block_a, block_b)


# ---------------------------------------------------------------------------
# Union-find over (norm_key, source_id) identity atoms
# ---------------------------------------------------------------------------

class UnionFind:
    def __init__(self):
        self.parent = {}

    def find(self, item):
        self.parent.setdefault(item, item)
        root = item
        while self.parent[root] != root:
            root = self.parent[root]
        while self.parent[item] != root:
            self.parent[item], item = root, self.parent[item]
        return root

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            # deterministic: smaller tuple becomes the root
            if rb < ra:
                ra, rb = rb, ra
            self.parent[rb] = ra

    def components(self):
        groups = {}
        for item in sorted(self.parent):
            groups.setdefault(self.find(item), []).append(item)
        return [sorted(members) for _, members in sorted(groups.items())]
