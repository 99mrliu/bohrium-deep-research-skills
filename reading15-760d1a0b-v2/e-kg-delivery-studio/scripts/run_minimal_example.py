#!/usr/bin/env python3
"""run_minimal_example.py - run the whole pipeline on the SYNTHETIC example.

Simulates the challenge runtime layout using ONLY this bundle's own scripts:

  examples/synthetic/input/            -> /input
  <temp dir>                           -> /app/work  (scratch, auto-removed)
  examples/synthetic/work/extractions.jsonl
                                       -> the model-written extraction artifact
  examples/synthetic/output/           -> /app/output

Everything in the example is SYNTHETIC, not real papers. The committed files
under examples/synthetic/output/ are regenerated by this script; they are
demo outputs, NOT formal case answers.

Usage:
  python3 scripts/run_minimal_example.py [--keep-work] [--run-meta]
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile

BUNDLE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog="run_minimal_example.py",
        description="Run the full e-kg-delivery-studio pipeline on the "
                    "SYNTHETIC example corpus (stdlib only).")
    ap.add_argument("--input",
                    default=os.path.join(BUNDLE, "examples", "synthetic", "input"),
                    help="simulated /input dir")
    ap.add_argument("--extractions",
                    default=os.path.join(BUNDLE, "examples", "synthetic", "work",
                                         "extractions.jsonl"),
                    help="model-written extraction artifact (SYNTHETIC)")
    ap.add_argument("--output",
                    default=os.path.join(BUNDLE, "examples", "synthetic", "output"),
                    help="simulated /app/output dir")
    ap.add_argument("--keep-work", action="store_true",
                    help="keep the scratch /app/work dir (printed to stdout)")
    ap.add_argument("--run-meta", action="store_true",
                    help="include a wall-clock run_meta block in result.json")
    args = ap.parse_args(argv)

    pipeline = os.path.join(BUNDLE, "scripts", "kg_pipeline.py")
    work = tempfile.mkdtemp(prefix="e_kg_delivery_work_")
    cmd = [sys.executable, pipeline, "all",
           "--input", args.input,
           "--work", work,
           "--extractions", args.extractions,
           "--output", args.output]
    if args.run_meta:
        cmd.append("--run-meta")
    print("$ " + " ".join(cmd))
    proc = subprocess.run(cmd)
    if proc.returncode != 0:
        print("pipeline FAILED with exit code %d" % proc.returncode)
        return proc.returncode

    print("\n--- outputs in %s ---" % args.output)
    total = 0
    for name in sorted(os.listdir(args.output)):
        path = os.path.join(args.output, name)
        if os.path.isfile(path):
            size = os.path.getsize(path)
            total += size
            print("  %-28s %8d bytes" % (name, size))
    print("  %-28s %8d bytes" % ("TOTAL", total))
    if args.keep_work:
        print("work dir kept at: %s" % work)
    else:
        shutil.rmtree(work, ignore_errors=True)
    print("example run OK (SYNTHETIC demo outputs, NOT formal case answers)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
